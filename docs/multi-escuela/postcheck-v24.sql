-- Read-only. Run on production AFTER V24 and BEFORE the switch of callers to the catalog.
-- Every row is something to review by hand; no rows = the catalog covers what the code uses today.
--   VARIANTE_O_DUPLICADO: an unclassified product (codigo NULL) whose concepto equals a classified
--     one ignoring case, accents and repeated/edge spaces (the normalization of
--     AlumnoServiceImpl.buscarProductoPorConcepto). id_menor = 1: findFirstByConcepto (collation
--     utf8mb4_0900_ai_ci) may return THIS product today instead of the classified one.
--   CODIGO_SIN_PRODUCTO: a name the code looks up has no product with exactly that concepto.
--   INSCRIPCION_SIN_TARIFA: alumno_deporte with tipo_tarifa but no tarifa_id.
SELECT 'VARIANTE_O_DUPLICADO' AS motivo, p.id AS id, p.concepto AS valor, c.codigo AS codigo,
       (p.id < c.id) AS id_menor
FROM producto p
JOIN producto c
  ON c.organizacion_id = p.organizacion_id
 AND c.codigo IS NOT NULL
 AND c.id <> p.id
WHERE p.organizacion_id = 1
  AND p.codigo IS NULL
  AND TRIM(REGEXP_REPLACE(p.concepto, '[[:space:]]+', ' ')) COLLATE utf8mb4_0900_ai_ci
      = TRIM(REGEXP_REPLACE(c.concepto, '[[:space:]]+', ' ')) COLLATE utf8mb4_0900_ai_ci
UNION ALL
SELECT 'CODIGO_SIN_PRODUCTO', NULL, NULL, e.codigo, NULL
FROM (
  SELECT 'MENSUALIDAD' AS codigo
  UNION ALL SELECT 'RESERVA_PLAZA' UNION ALL SELECT 'LICENCIA_FEDERATIVA'
  UNION ALL SELECT 'LICENCIA_TAEKWONDO_ADULTO' UNION ALL SELECT 'LICENCIA_TAEKWONDO_INFANTIL'
  UNION ALL SELECT 'LICENCIA_TAEKWONDO_DISCAPACIDAD' UNION ALL SELECT 'LICENCIA_TAEKWONDO_ADULTO_PROPORCIONAL'
  UNION ALL SELECT 'LICENCIA_TAEKWONDO_INFANTIL_PROPORCIONAL'
  UNION ALL SELECT 'LICENCIA_TAEKWONDO_DISCAPACIDAD_PROPORCIONAL'
  UNION ALL SELECT 'LICENCIA_KICKBOXING_ADULTO' UNION ALL SELECT 'LICENCIA_KICKBOXING_INFANTIL'
  UNION ALL SELECT 'COMPETIDOR_TAEKWONDO' UNION ALL SELECT 'COMPETIDOR_KICKBOXING'
  UNION ALL SELECT 'EXAMEN_BLANCO_AMARILLO' UNION ALL SELECT 'EXAMEN_AMARILLO'
  UNION ALL SELECT 'EXAMEN_AMARILLO_NARANJA' UNION ALL SELECT 'EXAMEN_NARANJA'
  UNION ALL SELECT 'EXAMEN_NARANJA_VERDE' UNION ALL SELECT 'EXAMEN_VERDE'
  UNION ALL SELECT 'EXAMEN_VERDE_AZUL' UNION ALL SELECT 'EXAMEN_AZUL'
  UNION ALL SELECT 'EXAMEN_AZUL_ROJO' UNION ALL SELECT 'EXAMEN_ROJO'
  UNION ALL SELECT 'EXAMEN_ROJO_NEGRO_1_PUM' UNION ALL SELECT 'EXAMEN_ROJO_NEGRO_2_PUM'
  UNION ALL SELECT 'EXAMEN_NEGRO_1_DAN' UNION ALL SELECT 'EXAMEN_NEGRO_2_DAN'
  UNION ALL SELECT 'EXAMEN_NEGRO_3_DAN' UNION ALL SELECT 'EXAMEN_ROJO_BORDADO'
  UNION ALL SELECT 'RECOMPENSA_BLANCO_AMARILLO' UNION ALL SELECT 'RECOMPENSA_AMARILLO'
  UNION ALL SELECT 'RECOMPENSA_AMARILLO_NARANJA' UNION ALL SELECT 'RECOMPENSA_NARANJA'
  UNION ALL SELECT 'RECOMPENSA_NARANJA_VERDE' UNION ALL SELECT 'RECOMPENSA_VERDE'
  UNION ALL SELECT 'RECOMPENSA_VERDE_AZUL' UNION ALL SELECT 'RECOMPENSA_AZUL'
  UNION ALL SELECT 'RECOMPENSA_AZUL_ROJO' UNION ALL SELECT 'RECOMPENSA_ROJO'
  UNION ALL SELECT 'RECOMPENSA_ROJO_BORDADO'
) e
WHERE NOT EXISTS (
  SELECT 1 FROM producto p
  WHERE p.organizacion_id = 1
    AND CONVERT(p.codigo USING utf8mb4) COLLATE utf8mb4_bin = CONVERT(e.codigo USING utf8mb4) COLLATE utf8mb4_bin
)
UNION ALL
SELECT 'INSCRIPCION_SIN_TARIFA', ad.id, CONVERT(ad.tipo_tarifa USING utf8mb4), NULL, NULL
FROM alumno_deporte ad
WHERE ad.organizacion_id = 1
  AND ad.tipo_tarifa IS NOT NULL
  AND ad.tarifa_id IS NULL;
