-- Read-only, COUNTS ONLY (no ids, names or concepts). Run on production AFTER V24 and again right
-- before the switch of callers (after db/resync/resync_catalogo_v24.sql). Every non-zero count is
-- something to review by hand.
--   variantes_o_duplicados: unclassified products (codigo NULL) whose concepto equals a classified
--     one ignoring case, accents and repeated/edge spaces (the normalization of
--     AlumnoServiceImpl.buscarProductoPorConcepto).
--   variantes_id_menor: of those, the ones with a LOWER id than the classified product:
--     findFirstByConcepto (collation utf8mb4_0900_ai_ci) may return them today instead.
--   codigos_sin_producto: names the code looks up with no product carrying their codigo.
--   productos_renombrados: classified products whose concepto no longer equals the known concepto
--     for their codigo.
--   examen_recompensa_sin_grado: classified EXAMEN/RECOMPENSA products without grado_id.
--   inscripciones_sin_tarifa: alumno_deporte with tipo_tarifa but no tarifa_id.
--   inscripciones_tarifa_distinta: tarifa_id whose tarifa.codigo differs from tipo_tarifa.
--   inscripciones_tarifa_sin_tipo: tarifa_id set but tipo_tarifa NULL.
--   tarifas_sin_disciplina: seeded tarifas with NULL disciplina_id although one is expected.
SELECT
  (SELECT COUNT(*)
   FROM producto p
   JOIN producto c
     ON c.organizacion_id = p.organizacion_id AND c.codigo IS NOT NULL AND c.id <> p.id
   WHERE p.organizacion_id = 1
     AND p.codigo IS NULL
     AND TRIM(REGEXP_REPLACE(p.concepto, '[[:space:]]+', ' ')) COLLATE utf8mb4_0900_ai_ci
         = TRIM(REGEXP_REPLACE(c.concepto, '[[:space:]]+', ' ')) COLLATE utf8mb4_0900_ai_ci
  ) AS variantes_o_duplicados,
  (SELECT COUNT(*)
   FROM producto p
   JOIN producto c
     ON c.organizacion_id = p.organizacion_id AND c.codigo IS NOT NULL AND c.id > p.id
   WHERE p.organizacion_id = 1
     AND p.codigo IS NULL
     AND TRIM(REGEXP_REPLACE(p.concepto, '[[:space:]]+', ' ')) COLLATE utf8mb4_0900_ai_ci
         = TRIM(REGEXP_REPLACE(c.concepto, '[[:space:]]+', ' ')) COLLATE utf8mb4_0900_ai_ci
  ) AS variantes_id_menor,
  (SELECT COUNT(*)
   FROM (
     SELECT 'MENSUALIDAD' AS codigo, 'MENSUALIDAD' AS concepto
     UNION ALL SELECT 'RESERVA_PLAZA', 'RESERVA DE PLAZA'
     UNION ALL SELECT 'LICENCIA_FEDERATIVA', 'LICENCIA FEDERATIVA'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_ADULTO', 'LICENCIA FEDERATIVA TAEKWONDO ADULTO'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_INFANTIL', 'LICENCIA FEDERATIVA TAEKWONDO INFANTIL'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_DISCAPACIDAD', 'LICENCIA FEDERATIVA TAEKWONDO DISCAPACIDAD'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_ADULTO_PROPORCIONAL', 'PARTE PROPORCIONAL LICENCIA FEDERATIVA TAEKWONDO ADULTO'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_INFANTIL_PROPORCIONAL', 'PARTE PROPORCIONAL LICENCIA FEDERATIVA TAEKWONDO INFANTIL'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_DISCAPACIDAD_PROPORCIONAL', 'PARTE PROPORCIONAL LICENCIA FEDERATIVA TAEKWONDO DISCAPACIDAD'
     UNION ALL SELECT 'LICENCIA_KICKBOXING_ADULTO', 'LICENCIA FEDERATIVA KICKBOXING ADULTO'
     UNION ALL SELECT 'LICENCIA_KICKBOXING_INFANTIL', 'LICENCIA FEDERATIVA KICKBOXING INFANTIL'
     UNION ALL SELECT 'COMPETIDOR_TAEKWONDO', 'TARIFA COMPETIDOR TAEKWONDO'
     UNION ALL SELECT 'COMPETIDOR_KICKBOXING', 'TARIFA COMPETIDOR KICKBOXING'
     UNION ALL SELECT 'EXAMEN_BLANCO_AMARILLO', 'DERECHO A EXAMEN BLANCO/AMARILLO'
     UNION ALL SELECT 'EXAMEN_AMARILLO', 'DERECHO A EXAMEN AMARILLO'
     UNION ALL SELECT 'EXAMEN_AMARILLO_NARANJA', 'DERECHO A EXAMEN AMARILLO/NARANJA'
     UNION ALL SELECT 'EXAMEN_NARANJA', 'DERECHO A EXAMEN NARANJA'
     UNION ALL SELECT 'EXAMEN_NARANJA_VERDE', 'DERECHO A EXAMEN NARANJA/VERDE'
     UNION ALL SELECT 'EXAMEN_VERDE', 'DERECHO A EXAMEN VERDE'
     UNION ALL SELECT 'EXAMEN_VERDE_AZUL', 'DERECHO A EXAMEN VERDE/AZUL'
     UNION ALL SELECT 'EXAMEN_AZUL', 'DERECHO A EXAMEN AZUL'
     UNION ALL SELECT 'EXAMEN_AZUL_ROJO', 'DERECHO A EXAMEN AZUL/ROJO'
     UNION ALL SELECT 'EXAMEN_ROJO', 'DERECHO A EXAMEN ROJO'
     UNION ALL SELECT 'EXAMEN_ROJO_NEGRO_1_PUM', 'DERECHO A EXAMEN ROJO/NEGRO 1º PUM'
     UNION ALL SELECT 'EXAMEN_ROJO_NEGRO_2_PUM', 'DERECHO A EXAMEN ROJO/NEGRO 2º PUM'
     UNION ALL SELECT 'EXAMEN_NEGRO_1_DAN', 'DERECHO A EXAMEN NEGRO 1º DAN'
     UNION ALL SELECT 'EXAMEN_NEGRO_2_DAN', 'DERECHO A EXAMEN NEGRO 2º DAN'
     UNION ALL SELECT 'EXAMEN_NEGRO_3_DAN', 'DERECHO A EXAMEN NEGRO 3º DAN'
     UNION ALL SELECT 'EXAMEN_ROJO_BORDADO', 'DERECHO A EXAMEN ROJO BORDADO'
     UNION ALL SELECT 'RECOMPENSA_BLANCO_AMARILLO', 'DERECHO CAMBIO A BLANCO-AMARILLO RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AMARILLO', 'DERECHO DE CAMBIO A AMARILLO POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AMARILLO_NARANJA', 'DERECHO DE CAMBIO A AMARILLO-NARANJA POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_NARANJA', 'DERECHO DE CAMBIO A NARANJA POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_NARANJA_VERDE', 'DERECHO DE CAMBIO A NARANJA-VERDE POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_VERDE', 'DERECHO DE CAMBIO A VERDE RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_VERDE_AZUL', 'DERECHO DE CAMBIO A VERDE-AZUL POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AZUL', 'DERECHO DE CAMBIO A AZUL POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AZUL_ROJO', 'DERECHO DE CAMBIO A AZUL-ROJO POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_ROJO', 'DERECHO DE CAMBIO A ROJO POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_ROJO_BORDADO', 'DERECHO DE CAMBIO A ROJO BORDADO POR RECOMPENSA'
   ) e
   WHERE NOT EXISTS (
     SELECT 1 FROM producto p
     WHERE p.organizacion_id = 1
       AND CONVERT(p.codigo USING utf8mb4) COLLATE utf8mb4_bin = CONVERT(e.codigo USING utf8mb4) COLLATE utf8mb4_bin
   )
  ) AS codigos_sin_producto,
  (SELECT COUNT(*)
   FROM producto p
   JOIN (
     SELECT 'MENSUALIDAD' AS codigo, 'MENSUALIDAD' AS concepto
     UNION ALL SELECT 'RESERVA_PLAZA', 'RESERVA DE PLAZA'
     UNION ALL SELECT 'LICENCIA_FEDERATIVA', 'LICENCIA FEDERATIVA'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_ADULTO', 'LICENCIA FEDERATIVA TAEKWONDO ADULTO'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_INFANTIL', 'LICENCIA FEDERATIVA TAEKWONDO INFANTIL'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_DISCAPACIDAD', 'LICENCIA FEDERATIVA TAEKWONDO DISCAPACIDAD'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_ADULTO_PROPORCIONAL', 'PARTE PROPORCIONAL LICENCIA FEDERATIVA TAEKWONDO ADULTO'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_INFANTIL_PROPORCIONAL', 'PARTE PROPORCIONAL LICENCIA FEDERATIVA TAEKWONDO INFANTIL'
     UNION ALL SELECT 'LICENCIA_TAEKWONDO_DISCAPACIDAD_PROPORCIONAL', 'PARTE PROPORCIONAL LICENCIA FEDERATIVA TAEKWONDO DISCAPACIDAD'
     UNION ALL SELECT 'LICENCIA_KICKBOXING_ADULTO', 'LICENCIA FEDERATIVA KICKBOXING ADULTO'
     UNION ALL SELECT 'LICENCIA_KICKBOXING_INFANTIL', 'LICENCIA FEDERATIVA KICKBOXING INFANTIL'
     UNION ALL SELECT 'COMPETIDOR_TAEKWONDO', 'TARIFA COMPETIDOR TAEKWONDO'
     UNION ALL SELECT 'COMPETIDOR_KICKBOXING', 'TARIFA COMPETIDOR KICKBOXING'
     UNION ALL SELECT 'EXAMEN_BLANCO_AMARILLO', 'DERECHO A EXAMEN BLANCO/AMARILLO'
     UNION ALL SELECT 'EXAMEN_AMARILLO', 'DERECHO A EXAMEN AMARILLO'
     UNION ALL SELECT 'EXAMEN_AMARILLO_NARANJA', 'DERECHO A EXAMEN AMARILLO/NARANJA'
     UNION ALL SELECT 'EXAMEN_NARANJA', 'DERECHO A EXAMEN NARANJA'
     UNION ALL SELECT 'EXAMEN_NARANJA_VERDE', 'DERECHO A EXAMEN NARANJA/VERDE'
     UNION ALL SELECT 'EXAMEN_VERDE', 'DERECHO A EXAMEN VERDE'
     UNION ALL SELECT 'EXAMEN_VERDE_AZUL', 'DERECHO A EXAMEN VERDE/AZUL'
     UNION ALL SELECT 'EXAMEN_AZUL', 'DERECHO A EXAMEN AZUL'
     UNION ALL SELECT 'EXAMEN_AZUL_ROJO', 'DERECHO A EXAMEN AZUL/ROJO'
     UNION ALL SELECT 'EXAMEN_ROJO', 'DERECHO A EXAMEN ROJO'
     UNION ALL SELECT 'EXAMEN_ROJO_NEGRO_1_PUM', 'DERECHO A EXAMEN ROJO/NEGRO 1º PUM'
     UNION ALL SELECT 'EXAMEN_ROJO_NEGRO_2_PUM', 'DERECHO A EXAMEN ROJO/NEGRO 2º PUM'
     UNION ALL SELECT 'EXAMEN_NEGRO_1_DAN', 'DERECHO A EXAMEN NEGRO 1º DAN'
     UNION ALL SELECT 'EXAMEN_NEGRO_2_DAN', 'DERECHO A EXAMEN NEGRO 2º DAN'
     UNION ALL SELECT 'EXAMEN_NEGRO_3_DAN', 'DERECHO A EXAMEN NEGRO 3º DAN'
     UNION ALL SELECT 'EXAMEN_ROJO_BORDADO', 'DERECHO A EXAMEN ROJO BORDADO'
     UNION ALL SELECT 'RECOMPENSA_BLANCO_AMARILLO', 'DERECHO CAMBIO A BLANCO-AMARILLO RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AMARILLO', 'DERECHO DE CAMBIO A AMARILLO POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AMARILLO_NARANJA', 'DERECHO DE CAMBIO A AMARILLO-NARANJA POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_NARANJA', 'DERECHO DE CAMBIO A NARANJA POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_NARANJA_VERDE', 'DERECHO DE CAMBIO A NARANJA-VERDE POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_VERDE', 'DERECHO DE CAMBIO A VERDE RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_VERDE_AZUL', 'DERECHO DE CAMBIO A VERDE-AZUL POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AZUL', 'DERECHO DE CAMBIO A AZUL POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_AZUL_ROJO', 'DERECHO DE CAMBIO A AZUL-ROJO POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_ROJO', 'DERECHO DE CAMBIO A ROJO POR RECOMPENSA'
     UNION ALL SELECT 'RECOMPENSA_ROJO_BORDADO', 'DERECHO DE CAMBIO A ROJO BORDADO POR RECOMPENSA'
   ) e
     ON CONVERT(p.codigo USING utf8mb4) COLLATE utf8mb4_bin = CONVERT(e.codigo USING utf8mb4) COLLATE utf8mb4_bin
   WHERE p.organizacion_id = 1
     AND (p.concepto IS NULL
          OR CAST(CONVERT(p.concepto USING utf8mb4) AS BINARY) <> CAST(CONVERT(e.concepto USING utf8mb4) AS BINARY))
  ) AS productos_renombrados,
  (SELECT COUNT(*)
   FROM producto p
   WHERE p.organizacion_id = 1
     AND p.codigo IS NOT NULL
     AND p.tipo IN ('EXAMEN', 'RECOMPENSA')
     AND p.grado_id IS NULL
  ) AS examen_recompensa_sin_grado,
  (SELECT COUNT(*)
   FROM alumno_deporte ad
   WHERE ad.organizacion_id = 1 AND ad.tipo_tarifa IS NOT NULL AND ad.tarifa_id IS NULL
  ) AS inscripciones_sin_tarifa,
  (SELECT COUNT(*)
   FROM alumno_deporte ad
   JOIN tarifa t ON t.id = ad.tarifa_id
   WHERE ad.organizacion_id = 1
     AND ad.tipo_tarifa IS NOT NULL
     AND CONVERT(t.codigo USING utf8mb4) COLLATE utf8mb4_bin <> CONVERT(ad.tipo_tarifa USING utf8mb4) COLLATE utf8mb4_bin
  ) AS inscripciones_tarifa_distinta,
  (SELECT COUNT(*)
   FROM alumno_deporte ad
   WHERE ad.organizacion_id = 1 AND ad.tipo_tarifa IS NULL AND ad.tarifa_id IS NOT NULL
  ) AS inscripciones_tarifa_sin_tipo,
  (SELECT COUNT(*)
   FROM tarifa t
   JOIN (
     SELECT 'FAMILIAR' AS codigo, 'TAEKWONDO' AS disciplina
     UNION ALL SELECT 'PADRES_HIJOS', 'TAEKWONDO'
     UNION ALL SELECT 'ADULTO_GRUPO', 'TAEKWONDO'
     UNION ALL SELECT 'INFANTIL_GRUPO', 'TAEKWONDO'
     UNION ALL SELECT 'HERMANOS', 'TAEKWONDO'
     UNION ALL SELECT 'INFANTIL', 'TAEKWONDO'
     UNION ALL SELECT 'ADULTO', 'TAEKWONDO'
     UNION ALL SELECT 'KICKBOXING', 'KICKBOXING'
     UNION ALL SELECT 'PILATES', 'PILATES'
     UNION ALL SELECT 'DEFENSA_PERSONAL_FEMENINA', 'DEFENSA_PERSONAL_FEMENINA'
   ) s
     ON CONVERT(t.codigo USING utf8mb4) COLLATE utf8mb4_bin = CONVERT(s.codigo USING utf8mb4) COLLATE utf8mb4_bin
   WHERE t.organizacion_id = 1
     AND s.disciplina IS NOT NULL
     AND t.disciplina_id IS NULL
  ) AS tarifas_sin_disciplina;
